// Writes data/stack-icons.ts with just the simple-icons paths the Tech Stack section uses,
// so the full icon set never ships to the browser. Run: node scripts/generate-stack-icons.mjs
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

const wanted = [
  "React", "Nextdotjs", "Typescript", "Tailwindcss",
  "Nodedotjs", "Express", "Postgresql", "Mongodb", "Prisma", "Python",
  "Flutter", "Firebase", "Vercel",
  "Googlegemini", "Anthropic",
];

const rows = wanted.map((name) => {
  const icon = si[`si${name}`];
  if (!icon) throw new Error(`simple-icons has no ${name}`);
  return `  ${JSON.stringify(icon.slug)}: { title: ${JSON.stringify(icon.title)}, hex: ${JSON.stringify("#" + icon.hex)}, path: ${JSON.stringify(icon.path)} },`;
});

writeFileSync(
  new URL("../data/stack-icons.ts", import.meta.url),
  `// Generated by scripts/generate-stack-icons.mjs from simple-icons (CC0). Do not edit by hand.\n\nexport type BrandIcon = { title: string; hex: string; path: string };\n\nexport const brandIcons: Record<string, BrandIcon> = {\n${rows.join("\n")}\n};\n`,
);
